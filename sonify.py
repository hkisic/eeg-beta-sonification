"""
Sound-sequence synthesis from beta motifs.

Each motif becomes a 1 s tone placed at its onset time, so the sound keeps the temporal
structure of the recorded beta activity:
  * pitch: a motif is treated as half a beta cycle, f = 0.5 / T (T = motif duration in s),
    multiplied by a transposition factor to reach the audible range;
  * timbre: fundamental + 3 harmonics (relative amplitudes 1, 0.5, 0.25, 0.12),
    exponential decay envelope exp(-0.2 t);
  * loudness: peak amplitude normalised to [0, 1] across the recording;
  * tones are summed (each scaled by 1/sqrt(N)), soft-clipped with tanh, normalised and
    written as a 16-bit stereo WAV at 44.1 kHz.

For every factor a scrambled control is also written: motif pitches and loudnesses are
randomly reassigned to the onset times (fixed seed), which keeps the distribution of
tones but breaks their temporal structure.

Factors 5, 10 and 20 are generated by default; participants chose the lowest (x5).

Usage
-----
    python -m sonification.sonify P1_motifs.csv --out-dir sounds --name P1
"""

import argparse
import os

import numpy as np
import pandas as pd
from scipy.io import wavfile

SFREQ = 44100
DECAY = 0.2
TONE_S = 1.0
FACTORS = (5, 10, 20)
SHUFFLE_SEED = 42


def motif_frequencies(motifs):
    """Instantaneous beta frequency of each motif (Hz), from its duration."""
    duration_s = (motifs["offset_ms"].to_numpy() - motifs["onset_ms"].to_numpy()) / 1000.0
    return 0.5 / duration_s


def generate_tone(frequency, duration_s=TONE_S, sfreq=SFREQ, amplitude=1.0, decay=DECAY):
    """Piano-like tone: fundamental + 3 harmonics with an exponential decay."""
    t = np.linspace(0, duration_s, int(sfreq * duration_s))
    s = (1.00 * np.sin(2 * np.pi * 1 * frequency * t)
         + 0.50 * np.sin(2 * np.pi * 2 * frequency * t)
         + 0.25 * np.sin(2 * np.pi * 3 * frequency * t)
         + 0.12 * np.sin(2 * np.pi * 4 * frequency * t))
    return s * np.exp(-decay * t) * amplitude


def soft_clip(signal, threshold=0.8):
    return np.tanh(signal / threshold) * threshold


def sonify(motifs, factor, shuffle=False, seed=SHUFFLE_SEED,
           sfreq=SFREQ, decay=DECAY, tone_s=TONE_S):
    """Audio signal in [-1, 1] for one transposition factor (optionally scrambled)."""
    onset_ms = motifs["onset_ms"].to_numpy()
    offset_ms = motifs["offset_ms"].to_numpy()
    amp = motifs["peak_amp"].to_numpy()
    n = len(motifs)
    freqs = motif_frequencies(motifs)
    amp_norm = (amp - amp.min()) / (amp.max() - amp.min())
    if shuffle:
        order = np.random.default_rng(seed).permutation(n)
        freqs, amp_norm = freqs[order], amp_norm[order]

    total = int(((offset_ms[-1] / 1000.0) + tone_s + 1.0) * sfreq)   # tail for the last note
    wave = np.zeros(total)
    for i in range(n):
        tone = generate_tone(freqs[i] * factor, tone_s, sfreq, amp_norm[i], decay)
        start = int((onset_ms[i] / 1000.0) * sfreq)
        end = min(start + len(tone), total)
        wave[start:end] += tone[:end - start] / np.sqrt(n)
    wave = soft_clip(wave)
    peak = np.max(np.abs(wave))
    return wave / peak if peak > 0 else wave


def write_wav(path, wave, sfreq=SFREQ):
    """16-bit stereo WAV."""
    pcm = (wave * 32767).astype(np.int16)
    wavfile.write(path, sfreq, np.stack([pcm, pcm], axis=1))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("motifs_csv", help="output of sonification.motifs")
    p.add_argument("--out-dir", required=True)
    p.add_argument("--name", required=True, help="prefix of the WAV files, e.g. P1_nomusic")
    p.add_argument("--factors", type=float, nargs="+", default=list(FACTORS))
    p.add_argument("--no-scrambled", action="store_true", help="skip the scrambled control")
    a = p.parse_args()

    motifs = pd.read_csv(a.motifs_csv)
    f = motif_frequencies(motifs)
    print(f"{len(motifs)} motifs, frequency {f.mean():.1f} Hz on average ({f.min():.1f}-{f.max():.1f} Hz)")
    os.makedirs(a.out_dir, exist_ok=True)
    for factor in a.factors:
        label = f"x{factor:g}"
        for shuffle in ([False] if a.no_scrambled else [False, True]):
            wave = sonify(motifs, factor, shuffle=shuffle)
            path = os.path.join(a.out_dir, f"{a.name}_sonified_{label}{'_scrambled' if shuffle else ''}.wav")
            write_wav(path, wave)
            print(f"Saved {path}")


if __name__ == "__main__":
    main()
